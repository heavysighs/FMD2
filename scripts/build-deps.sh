# InternetTools regex engine data (README: FLRE.pas + PUCU.pas live in data/)
if [ -d "$THIRD/internettools" ]; then
  IT="$THIRD/internettools"
  [ -f "$IT/data/FLRE.pas" ] || clone flre https://github.com/BeRo1985/flre.git 147b5178d62f08d133954044769033d5a9d86861
  [ -f "$IT/data/PUCU.pas" ] || clone pucu https://github.com/BeRo1985/pucu.git 60ca8230e47e12438a29fc53806936aa2b627dc5
  [ -f "$IT/data/FLRE.pas" ] || cp "$THIRD/flre/src/FLRE.pas" "$IT/data/FLRE.pas"
  [ -f "$IT/data/PUCU.pas" ] || cp "$THIRD/pucu/src/PUCU.pas" "$IT/data/PUCU.pas"
fi

# --- laz_synapse: FMD's vendored synapse (baseunits/synapse) is what upstream
# actually compiles (md.lpi OtherUnitFiles) and it is self-consistent on Linux.
# External forks fail to build here (hakansimsek: synsock.inet_addr missing),
# so generate a package over the vendored copy instead.
GEN="$THIRD/fmd-laz-synapse"
mkdir -p "$GEN"
{
  echo '<?xml version="1.0" encoding="UTF-8"?>'
  echo '<CONFIG>'
  echo '  <Package Version="5">'
  echo '    <Name Value="laz_synapse"/>'
  echo '    <Type Value="RunAndDesignTime"/>'
  echo '    <AddToProjectUsesSection Value="False"/>'
  echo '    <Author Value="FMD2 vendored synapse package (generated by scripts/build-deps.sh)"/>'
  echo '    <CompilerOptions>'
  echo '      <Version Value="11"/>'
  echo '      <SearchPaths>'
  echo '        <OtherUnitFiles Value="../../baseunits/synapse"/>'
  echo '        <UnitOutputDirectory Value="lib/$(TargetCPU)-$(TargetOS)"/>'
  echo '      </SearchPaths>'
  echo '    </CompilerOptions>'
  echo '    <Description Value="Synapse networking library (vendored FMD2 copy)"/>'
  echo '    <License Value="Modified LGPL"/>'
  n=0; items=""
  # Windows-only synapse units: not referenced outside synapse (audit §6.3),
  # cannot compile on Linux (Crypt32/Windows/SBB APIs) — excluded from package.
  EXCLUDE="Crypt32 ssl_openssl_capi ssl_sbb ssl_sbb16 ssl_cryptlib ssl_libssh2 ssl_streamsec"
  for f in "$ROOT"/baseunits/synapse/*.pas; do
    base="$(basename "$f" .pas)"
    skip=0
    for x in $EXCLUDE; do [ "$base" = "$x" ] && skip=1 && break; done
    [ "$skip" = 1 ] && continue
    n=$((n+1))
    items="$items      <Item$n>
        <Filename Value=\"../../baseunits/synapse/$base.pas\"/>
        <UnitName Value=\"$base\"/>
      </Item$n>
"
  done
  echo "    <Files Count=\"$n\">"
  printf '%s' "$items"
  echo '    </Files>'
  echo '    <RequiredPkgs Count="1">'
  echo '      <Item1><PackageName Value="FCL"/></Item1>'
  echo '    </RequiredPkgs>'
  echo '    <UsageOptions>'
  echo '      <UnitPath Value="$(PkgOutDir)"/>'
  echo '    </UsageOptions>'
  echo '    <PublishOptions><Version Value="2"/></PublishOptions>'
  echo '  </Package>'
  echo '</CONFIG>'
} > "$GEN/laz_synapse.lpk"
echo "gen   $GEN/laz_synapse.lpk ($(grep -c '<Item' <<<"$(grep -A200 '<Files' "$GEN/laz_synapse.lpk")" || true) entries)"

# --- Linux patches for pinned upstream packages (idempotent) -----------------
# UP1: virtualtreeview_package: units/$(LCLWidgetType) has no dir for qt6
#      (repo ships units/qt, units/gtk2 …) → FakeActiveX not found on qt6.
vt_lpk="$THIRD/virtualtreeview/virtualtreeview_package.lpk"
if grep -q 'Value="units/\$(LCLWidgetType)"' "$vt_lpk"; then
  sed -i 's|Value="units/\$(LCLWidgetType)"|Value="units/$(LCLWidgetType);units/qt;units/gtk2"|' "$vt_lpk"
  echo "patch virtualtreeview_package.lpk: add units/qt,units/gtk2 fallback"
fi
# UP1b: include/intf/$(LCLWidgetType) has no qt6 dir either (vtgraphicsi.inc …)
if grep -q 'Value="include/intf/\$(LCLWidgetType);units;include/intf"' "$vt_lpk"; then
  sed -i 's|Value="include/intf/\$(LCLWidgetType);units;include/intf"|Value="include/intf/$(LCLWidgetType);units;include/intf;include/intf/qt;include/intf/gtk2"|' "$vt_lpk"
  echo "patch virtualtreeview_package.lpk: add include/intf/qt,gtk2 fallback"
fi
# UP1c: include/intf/qt/vtgraphicsi.inc hard-references unit `qt4` (dead since
#       Lazarus 2.x; only the `uses` line mentions it) → retarget to qt6.
if grep -q 'qt4, qtobjects' "$THIRD/virtualtreeview/include/intf/qt/vtgraphicsi.inc"; then
  sed -i 's|qt4, qtobjects|qt6, qtobjects|' "$THIRD/virtualtreeview/include/intf/qt/vtgraphicsi.inc"
  echo "patch virtualtreeview include/intf/qt/vtgraphicsi.inc: qt4 -> qt6"
fi
# UP3: VirtualTrees.pas — unqualified 3-arg Move() resolves to a 2-arg Classes
#      Move in this FPC/scope; qualify as System.Move (3 call sites).
if grep -q '[^m.]Move(FPositionToIndex\[' "$THIRD/virtualtreeview/VirtualTrees.pas"; then
  sed -i 's|\([^m.]\)Move(FPositionToIndex\[|\1System.Move(FPositionToIndex[|g' "$THIRD/virtualtreeview/VirtualTrees.pas"
  echo "patch VirtualTrees.pas: Move(FPositionToIndex -> System.Move (3 sites)"
fi
# UP2: internettools.lpk: synapse (httpsend) not declared as dependency.
it_lpk="$THIRD/internettools/internettools.lpk"
if ! grep -q '<PackageName Value="laz_synapse"/>' "$it_lpk"; then
  python3 - "$it_lpk" <<'EOF'
import sys
p = sys.argv[1]
s = open(p).read()
old = '<RequiredPkgs Count="1">\n      <Item1>\n        <PackageName Value="FCL"/>\n      </Item1>\n    </RequiredPkgs>'
new = '<RequiredPkgs Count="2">\n      <Item1>\n        <PackageName Value="FCL"/>\n      </Item1>\n      <Item2>\n        <PackageName Value="laz_synapse"/>\n      </Item2>\n    </RequiredPkgs>'
assert old in s, "internettools RequiredPkgs block not found — upstream layout changed"
open(p, 'w').write(s.replace(old, new, 1))
EOF
  echo "patch internettools.lpk: +RequiredPkgs laz_synapse"
fi

# --- duk_module_duktape (duktape extras, MIT): system libduktape.so does not
#     export duk_module_duktape_init, but JS require() inside Duktape.ExecJS
#     needs it (e.g. lua/modules/MangaGo.lua requires utils/crypto-js.min.js).
#     Fetched raw at duktape v2.7.0 (matches Arch libduktape 2.7.0), sha256-pinned.
DM="$THIRD/duktape-module"
mkdir -p "$DM"
fetch_dm() { # fetch_dm <file> <sha256>
  local f="$DM/$1" sha="$2"
  if [ -f "$f" ] && [ "$(sha256sum "$f" | cut -d' ' -f1)" = "$sha" ]; then return 0; fi
  curl -fsSL -o "$f" "https://raw.githubusercontent.com/svaarala/duktape/v2.7.0/extras/module-duktape/$1" \
    || { echo "fetch $1 failed"; exit 1; }
  echo "$sha  $f" | sha256sum -c - || { echo "sha256 mismatch for $1"; exit 1; }
}
fetch_dm duk_module_duktape.c 5b433db34f6eafca77a412c8acc2e96486b38e8d7d25a0b54c9bd0951310274f
fetch_dm duk_module_duktape.h 07c200655f5a0d75f1d4675abb16924125f0b3deb8b79d92b962545960ec4793
if [ ! -f "$DM/duk_module_duktape.o" ] || [ "$DM/duk_module_duktape.c" -nt "$DM/duk_module_duktape.o" ] || [ "$DM/duk_module_duktape.h" -nt "$DM/duk_module_duktape.o" ]; then
  cc -c -O2 -fPIC -I"$DM" -o "$DM/duk_module_duktape.o" "$DM/duk_module_duktape.c" \
    || { echo "compile duk_module_duktape.c failed"; exit 1; }
  echo "OK    duk_module_duktape.o"
fi

# --- Register package links with lazbuild (idempotent) -----------------------
register() {
  local lpk="$1"
  $LAZBUILD --add-package-link "$lpk" 2>&1 | grep -E "Registering|Error" || true
}
for lpk in \
  "$GEN/laz_synapse.lpk" \
  "$THIRD/dcpcrypt/src/dcpcrypt.lpk" \
  "$THIRD/richmemo/richmemopackage.lpk" \
  "$THIRD/richmemo/richmemo_design.lpk" \
  "$THIRD/customcontrols/Core/customcontrols.lpk" \
  "$THIRD/customcontrols/Addon/MultiLog/customcontrols_addon_multilog.lpk" \
  "$THIRD/metadarkstyle/metadarkstyle.lpk" \
  "$THIRD/metadarkstyle/metadarkstyledsgn.lpk" \
  "$THIRD/virtualtreeview/virtualtreeview_package.lpk" \
  "$THIRD/multilog/multiloglaz.lpk" \
  "$THIRD/internettools/internettools.lpk"
do register "$lpk"; done

