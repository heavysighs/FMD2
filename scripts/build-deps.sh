# --- duk_module_duktape (duktape extras, MIT): system libduktape.so does not
#     export duk_module_duktape_init, but JS require() inside Duktape.ExecJS
#     needs it (e.g. lua/modules/MangaGo.lua requires utils/crypto-js.min.js).
#     Fetched raw at duktape v2.7.0 (matches Arch libduktape 2.7.0), sha256-pinned.
DM="$THIRD/duktape-module"
mkdir -p "$DM"
fetch_dm() { # fetch_dm <file> <sha256>
  local f="$DM/$1" sha="$2"
  if [ -f "$f" ] && [ "$(sha256sum "$f" | cut -d' ' -f1)" = "$sha" ]; then return 0; fi
  curl -fsSL -o "$f" "https://raw.githubusercontent.com/svaarala/duktape/v2.7.0/extras/module-duktape/$1" \
    || { echo "fetch $1 failed"; exit 1; }
  echo "$sha  $f" | sha256sum -c - || { echo "sha256 mismatch for $1"; exit 1; }
}
fetch_dm duk_module_duktape.c 5b433db34f6eafca77a412c8acc2e96486b38e8d7d25a0b54c9bd0951310274f
fetch_dm duk_module_duktape.h 07c200655f5a0d75f1d4675abb16924125f0b3deb8b79d92b962545960ec4793
if [ ! -f "$DM/duk_module_duktape.o" ] || [ "$DM/duk_module_duktape.c" -nt "$DM/duk_module_duktape.o" ] || [ "$DM/duk_module_duktape.h" -nt "$DM/duk_module_duktape.o" ]; then
  cc -c -O2 -fPIC -I"$DM" -o "$DM/duk_module_duktape.o" "$DM/duk_module_duktape.c" \
    || { echo "compile duk_module_duktape.c failed"; exit 1; }
  echo "OK    duk_module_duktape.o"
fi

