#!/usr/bin/env bash
# build-deps.sh — fetch pinned third-party Lazarus packages into 3rd/, register
# them with lazbuild, apply Linux patches, and compile them (tasks T006/T016).
# Every URL below was verified reachable (git ls-remote / GitHub API) before pinning.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
THIRD="$ROOT/3rd"
LAZARUSDIR="${LAZARUSDIR:-/usr/lib/lazarus}"
mkdir -p "$THIRD"

LAZBUILD="lazbuild --lazarusdir=$LAZARUSDIR"
command -v lazbuild >/dev/null || { echo "lazbuild not found"; exit 1; }

clone() { # clone <name> <url> <commit>
  local name="$1" url="$2" sha="$3"
  if [ -d "$THIRD/$name/.git" ]; then
    echo "have  $name"
  else
    echo "fetch $name <- $url @ ${sha:0:7}"
    git clone -q "$url" "$THIRD/$name"
  fi
  git -C "$THIRD/$name" checkout -q "$sha"
}

